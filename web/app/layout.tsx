// Link previews need absolute URLs: set NEXT_PUBLIC_SITE_URL to the public origin when building for a deployment
// (README, web section). Without it, previews point at the local server of `npm run serve`.
const SITE_URL = process.env.NEXT_PUBLIC_SITE_URL || "http://localhost:3000";
const DESCRIPTION = "Exam papers sealed under a double lock: drand timelock and the centre key.";
const SHARE_TITLE = "SealHour: exam papers sealed until the hour";

// Icons, manifest and preview images are files in this folder (icon.svg, favicon.ico, apple-icon.png, manifest.json,
// opengraph-image.png, twitter-image.png), generated by scripts/brand.mjs; Next links them in the head.
export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title: { default: "SealHour", template: "%s | SealHour" },
  description: DESCRIPTION,
  applicationName: "SealHour",
  openGraph: { type: "website", siteName: "SealHour", title: SHARE_TITLE, description: DESCRIPTION, url: "/" },
  twitter: { card: "summary_large_image", title: SHARE_TITLE, description: DESCRIPTION },
};

export const viewport: Viewport = { width: "device-width", initialScale: 1, themeColor: "#465dff" };

// Before first paint, like the template's config.js: saved theme and sidenav size for the viewport (media queries).
// Keys and sizes match components/Shell.tsx (THEME_KEY, SIDENAV_KEY, fitSize).
const FIRST_PAINT = `(function(){var h=document.documentElement,s=null;try{var t=localStorage.getItem("sealhour.theme");if(t!=="dark"&&t!=="light")t=matchMedia("(prefers-color-scheme: dark)").matches?"dark":"light";h.setAttribute("data-bs-theme",t);s=localStorage.getItem("sealhour.sidenav");if(s!=="sm-hover"&&s!=="sm-hover-active")s=null}catch(e){}h.setAttribute("data-sidenav-size",matchMedia("(max-width: 767.98px)").matches?"full":matchMedia("(max-width: 1140px)").matches?"condensed":s||"sm-hover-active")})();`;

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html
      lang="en"
      data-bs-theme="light"
      data-layout="vertical"
      data-layout-mode="fluid"
      data-topbar-color="light"
      data-menu-color="dark"
      data-sidenav-size="sm-hover-active"
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: FIRST_PAINT }} />
      </head>
      <body>
        <a className="skip visually-hidden-focusable" href="#main">
          Skip to content
        </a>
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
