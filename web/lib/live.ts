export async function loadLiveBase(): Promise<LiveBase> {
  const res = await fetch("/config.live.json", { cache: "no-store" });
  if (!res.ok) throw new Error(`config.live.json: HTTP ${res.status}`);
  const b = (await res.json()) as LiveBase;
  if (b.chainId !== LIVE_CHAIN_ID || !b.registry?.address || !Array.isArray(b.abi) || !b.rpcUrls?.length || !b.beaconUrls?.length) {
    throw new Error("config.live.json: chainId 84532, registry, abi, rpcUrls and beaconUrls are required");
  }
  // The beacon pin is fixed: drand quicknet. The shared registry's own pin is checked by walletConfig.
  const hex = (h: string) => String(h ?? "").replace(/^0x/i, "").toLowerCase();
  if (hex(b.beaconChainHash) !== QUICKNET_PIN.chainHash || hex(b.beaconPublicKey) !== QUICKNET_PIN.publicKey || b.genesisTime !== QUICKNET_GENESIS || b.period !== QUICKNET_PERIOD) {
    throw new Error("BeaconPinMismatch");
  }
  return b;
}

