  if (b.chainId !== LIVE_CHAIN_ID || base.chainId !== LIVE_CHAIN_ID) throw new Error("burner wallets are for Base Sepolia (84532) only");
  if (!b.registry) throw new Error("the solo test registry is not deployed yet");
