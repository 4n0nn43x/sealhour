/* ---------------------------------------------------------------- testnet storage namespace */

export const TESTNET_NS = "sealhour.testnet.";
function tget<T>(key: string): T | null {
  const raw = storage.get(TESTNET_NS + key);
  if (!raw) return null;
  try {
    return JSON.parse(raw) as T;
  } catch {
    return null;
  }
}
const tset = (key: string, v: unknown) => storage.set(TESTNET_NS + key, JSON.stringify(v));

export type LiveSession = { kind: "wallet" } | { kind: "solo" };
export const readSession = () => tget<LiveSession>("session");
export const saveSession = (s: LiveSession | null) => (s ? tset("session", s) : storage.remove(TESTNET_NS + "session"));
/** Remembered wallet (rdns, else uuid), to reconnect without a popup. */
export const readWalletHint = () => tget<string>("wallet");
export const saveWalletHint = (h: string | null) => (h ? tset("wallet", h) : storage.remove(TESTNET_NS + "wallet"));

