function withLocalKeys(cfg: AppConfig, c: DemoCentre, chain?: { centreId: string; name: string }): DemoCentre {
  const centreId = chain?.centreId ?? c.centreId;
  return { ...c, centreId, name: chain?.name ?? c.name, identity: centreIdentity(cfg, centreId), rcHex: centreRc(cfg, cfg.demo.examId, centreId) };
}

/** Roles of a live session. Solo: every burner persona, centres resolved on chain by operator (registered name and
 *  id), with this device's identity and r_c. Wallet: only what the connected address is on chain (office(),
 *  committeesOf incl. the reserve, centre operator via allCentres + getCentre), then the public juror. */
export async function liveRoles(cfg: AppConfig, kind: LiveSession["kind"], address: string | null): Promise<Role[]> {
  const chainCentres = await readAllCentres(cfg);
  const byOperator = (a: string) => chainCentres.filter((c) => c.operator.toLowerCase() === a.toLowerCase());
  if (kind === "solo") {
    return listRoles(cfg).map((r) => (r.kind === "centre" && r.centre ? { ...r, name: byOperator(r.centre.address)[0]?.name ?? r.name, centre: withLocalKeys(cfg, r.centre, byOperator(r.centre.address)[0]) } : r));
  }
  const juror: Role = { key: "juror", kind: "juror", name: "Juror" };
  if (!address) return [juror];
  const me = { address, privateKey: null };
  const roles: Role[] = [];
  if (cfg.deployment.office.toLowerCase() === address.toLowerCase()) roles.push({ key: "office", kind: "office", name: "Office", account: me });
  const [committees, reserve] = await registry(cfg).committeesOf(cfg.demo.examId);
  const list: string[] = [...committees];
  list.forEach((a, i) => {
    if (a.toLowerCase() !== address.toLowerCase()) return;
    const committee = { ...me, setIndex: i, label: LABELS[i] ?? String.fromCharCode(65 + i) };
    roles.push({ key: `committee-${i}`, kind: "committee", name: committee.label, account: me, committee, index: i });
  });
  if (String(reserve).toLowerCase() === address.toLowerCase()) {
    const committee = { ...me, setIndex: list.length, label: "R" };
    roles.push({ key: `committee-${list.length}`, kind: "committee", name: "R", account: me, committee, index: list.length });
  }
  byOperator(address).forEach((c, i) => {
    const centre = withLocalKeys(cfg, { centreId: c.centreId, name: c.name, address, privateKey: null, identity: "", recipient: "", rcHex: "" });
    roles.push({ key: `centre-${i}`, kind: "centre", name: c.name, account: me, centre, index: i });
  });
  roles.push(juror);
  return roles;
}

/* ---------------------------------------------------------------- solo test: funding, deploy, leftovers */

/** Gas each burner may spend, from a measured run (deploy 3.04 M, registerCentreOperator 125 to 142 k,
 *  freezeCentresWithKeys 373 k, createExam 156 k, postPackageData 578 to 617 k, submitPackage 103 k, burnSet 59 k,
 *  setCentreKey 52 k, joinExam 561 k) plus one plain transfer back to the funder. */
const GAS = {
  office: 3_100_000 + 4 * 150_000 + 400_000 + 300_000 + 11 * 21_000,
  committee: 650_000 + 110_000 + 60_000 + 21_000,
  centre: 60_000 + 580_000 + 21_000,
  juror: 60_000 + 21_000,
};
/** Funding margin over today's fees (base fee and L1 data fee changes). */
const MARGIN = 2n;
/** Calldata bytes each burner posts, for its L1 data fee: the office deploys the bytecode and sends small calls and
 *  transfers; a committee posts its package (incompressible ciphertexts, a measured bundle is about 23 KiB at
 *  postPackageData 600 k gas); a centre sends setCentreKey and joinExam (tlocked r_c up to 1 KiB); the juror a flag. */
const L1_BYTES = { office: 4096, committee: 32_768 + 512, centre: 2048, juror: 512 };
/** A plain transfer (the funding transaction, a leftover return), for its L1 data fee. */
const TRANSFER_BYTES = 200n;
/** Fees may rise this much (percent) between the shown plan and the click before the user is asked again. */
const FEE_TOLERANCE_PCT = 20n;
const GAS_ORACLE = "0x420000000000000000000000000000000000000F";
const ORACLE = new Interface(["function getL1Fee(bytes) view returns (uint256)"]);

/** L1 data fee per calldata byte from the OP Stack GasPriceOracle, on incompressible bytes like the ciphertexts.
 *  0 on a chain without the oracle (the local rehearsal chain); an RPC failure throws. */
async function l1FeePerByte(p: JsonRpcProvider): Promise<bigint> {
  if ((await p.getCode(GAS_ORACLE)) === "0x") return 0n;
  const n = 24_576;
  const fee = BigInt(await p.call({ to: GAS_ORACLE, data: ORACLE.encodeFunctionData("getL1Fee", [randomBytes(n)]) }));
  return fee / BigInt(n) + 1n;
}

export interface FundingPlan {
  maxFeePerGas: bigint;
  /** Wei per burner: office, each committee (4 and the reserve), each centre, juror. */
  office: bigint;
  committee: bigint;
  centre: bigint;
  juror: bigint;
  total: bigint;
  /** Fee of the funding transaction itself (gas and L1 data, with the margin), paid by the wallet on top of total. */
  fundFee: bigint;
}

export function liveProvider(base: LiveBase): JsonRpcProvider {
  return getProvider(liveConfig(base, base.registry.address, base.registry.office, {} as DemoState));
}

export async function fundingPlan(base: LiveBase): Promise<FundingPlan> {
  const p = liveProvider(base);
  const [fee, l1] = await Promise.all([p.getFeeData(), l1FeePerByte(p)]);
  const maxFeePerGas = fee.maxFeePerGas ?? fee.gasPrice ?? 0n;
  if (maxFeePerGas <= 0n) throw new Error("no fee data from the RPC");
  const wei = (gas: number, bytes: number) => (BigInt(gas) * maxFeePerGas + BigInt(bytes) * l1) * MARGIN;
  const deployBytes = Math.ceil((base.bytecode.length - 2) / 2) + 4 * 32 + 160;
  const x = { office: wei(GAS.office, deployBytes + L1_BYTES.office), committee: wei(GAS.committee, L1_BYTES.committee), centre: wei(GAS.centre, L1_BYTES.centre), juror: wei(GAS.juror, L1_BYTES.juror) };
  const fundFee = (21_000n * maxFeePerGas + TRANSFER_BYTES * l1) * MARGIN;
  return { maxFeePerGas, ...x, total: x.office + 5n * x.committee + 4n * x.centre + x.juror, fundFee };
}

/** Fees rose beyond the tolerance since the plan was shown: nothing was sent, the new plan is attached. */
export class FeesChangedError extends Error {
  constructor(readonly plan: FundingPlan) {
    super("FeesChanged");
  }
}

export interface SetupStep {
  key: "keys" | "fund" | "distribute" | "deploy";
  hash?: string;
  address?: string;
}

/** Nonce of address once no transaction of it is pending (a previous attempt may still be in flight). */
async function settledNonce(p: JsonRpcProvider, address: string): Promise<number> {
  for (let i = 0; i < 30; i++) {
    const [latest, pending] = await Promise.all([p.getTransactionCount(address, "latest"), p.getTransactionCount(address, "pending")]);
    if (latest === pending) return latest;
    await new Promise((r) => setTimeout(r, 2000));
  }
  throw new Error("PendingTx");
}

/** Solo test, resumable: burner keys are saved before any transfer and reused by a retry. The funder tops up the
 *  office burner (one wallet confirmation, skipped when it already holds enough), the office burner pays the
 *  burners still short of their budget and deploys a fresh SealRegistry pinned to drand quicknet (a deploy that
 *  landed in a failed attempt is found, not repeated). shown: the plan the user saw; a fee rise beyond
 *  FEE_TOLERANCE_PCT throws FeesChangedError before anything is sent. A new test is refused while the previous
 *  test's burners hold more than dust (return or export them first). */
export async function setupSolo(base: LiveBase, funder: Signer, shown: FundingPlan, onStep: (s: SetupStep) => void): Promise<Burners> {
  const provider = liveProvider(base);
  const net = await funder.provider?.getNetwork();
  if (Number(net?.chainId) !== LIVE_CHAIN_ID) throw new Error("WrongChain");
  const from = await funder.getAddress();
  const fresh = await fundingPlan(base);
  if (fresh.total * 100n > shown.total * (100n + FEE_TOLERANCE_PCT)) throw new FeesChangedError(fresh);
  const plan = shown;

  let b = readBurners();
  if (b && (b.registry || b.chainId !== LIVE_CHAIN_ID)) {
    if (await burnersHoldFunds(base, b)) throw new Error("BurnersHoldFunds");
    b = null; // a finished test with dust only: a new one replaces it
  }
  if (b && b.funder.toLowerCase() !== from.toLowerCase()) throw new Error("BurnersOtherFunder");
  if (!b) {
    const key = () => Wallet.createRandom().privateKey;
    b = {
      chainId: LIVE_CHAIN_ID,
      funder: from,
      created: new Date().toISOString(),
      examLabel: `sealhour-live-${Date.now()}`,
      keys: { office: key(), committees: LABELS.map(key), reserve: key(), centres: CENTRE_NAMES.map(key), juror: key() },
    };
    saveBurners(b);
  }
  onStep({ key: "keys" });

  const office = new Wallet(b.keys.office, provider);
  let nonce = await settledNonce(provider, office.address);
  const done = async (bb: Burners, hash?: string) => {
    saveBurners(bb);
    onStep({ key: "deploy", hash, address: bb.registry });
    return bb;
  };
  if (b.deployNonce !== undefined && nonce > b.deployNonce) {
    const addr = getCreateAddress({ from: office.address, nonce: b.deployNonce });
    if ((await provider.getCode(addr)) !== "0x") return done({ ...b, registry: addr });
  }

  const pay: [string, bigint][] = [
    ...[...b.keys.committees, b.keys.reserve].map((k) => [new Wallet(k).address, plan.committee] as [string, bigint]),
    ...b.keys.centres.map((k) => [new Wallet(k).address, plan.centre] as [string, bigint]),
    [new Wallet(b.keys.juror).address, plan.juror],
  ];
  const held = await Promise.all(pay.map(([a]) => provider.getBalance(a)));
  const short = pay.map(([to, v], i) => [to, v - held[i]!] as [string, bigint]).filter(([, v]) => v > 0n);
  const need = plan.office + short.reduce((a, [, v]) => a + v, 0n) - (await provider.getBalance(office.address));
  if (need > 0n) {
    if ((await provider.getBalance(from)) < need + plan.fundFee) throw new Error("NotEnoughTestEth");
    const fund = await funder.sendTransaction({ to: office.address, value: need, chainId: LIVE_CHAIN_ID });
    await fund.wait();
    onStep({ key: "fund", hash: fund.hash });
  } else onStep({ key: "fund" });

  // One by one, explicit nonces (a "pending" count read right after a transfer can come from a lagging node): a
  // failed broadcast stops here and leaves no nonce gap; a retry pays only the burners still short.
  const sent: TransactionResponse[] = [];
  for (const [to, value] of short) sent.push(await office.sendTransaction({ to, value, nonce: nonce++, chainId: LIVE_CHAIN_ID }));
  await Promise.all(sent.map((tx) => tx.wait()));
  onStep({ key: "distribute", hash: sent[sent.length - 1]?.hash });

  b = { ...b, deployNonce: nonce };
  saveBurners(b);
  const factory = new ContractFactory(base.abi, base.bytecode, office);
  const c = await factory.deploy(QUICKNET_GENESIS, QUICKNET_PERIOD, "0x" + QUICKNET_PIN.chainHash, "0x" + QUICKNET_PIN.publicKey, { nonce, chainId: LIVE_CHAIN_ID });
  const receipt = await c.deploymentTransaction()!.wait();
  return done({ ...b, registry: await c.getAddress(), deployBlock: receipt?.blockNumber ?? undefined }, c.deploymentTransaction()!.hash);
}

export function burnerAddresses(b: Burners): { label: string; address: string; key: string }[] {
  return [
    { label: "Office", key: b.keys.office },
    ...b.keys.committees.map((k, i) => ({ label: `Committee ${LABELS[i]}`, key: k })),
    { label: "Committee R", key: b.keys.reserve },
    ...b.keys.centres.map((k, i) => ({ label: CENTRE_NAMES[i]!, key: k })),
    { label: "Juror", key: b.keys.juror },
  ].map((x) => ({ ...x, address: new Wallet(x.key).address }));
}

export async function burnersBalance(base: LiveBase, b: Burners): Promise<bigint> {
  const p = liveProvider(base);
  const all = await Promise.all(burnerAddresses(b).map((x) => p.getBalance(x.address)));
  return all.reduce((a, x) => a + x, 0n);
}

/** Fee kept by a burner for its return transfer (twice today's gas and L1 data fee). A balance at most twice that
 *  is dust: not worth returning. */
async function returnFee(p: JsonRpcProvider) {
  const [fee, l1] = await Promise.all([p.getFeeData(), l1FeePerByte(p)]);
  const maxFeePerGas = fee.maxFeePerGas ?? fee.gasPrice ?? 0n;
  return { maxFeePerGas, maxPriorityFeePerGas: fee.maxPriorityFeePerGas ?? 0n, cost: (21_000n * maxFeePerGas + TRANSFER_BYTES * l1) * 2n };
}

/** True when a burner holds more than dust. */
export async function burnersHoldFunds(base: LiveBase, b: Burners): Promise<boolean> {
  const p = liveProvider(base);
  const { cost } = await returnFee(p);
  const all = await Promise.all(burnerAddresses(b).map((x) => p.getBalance(x.address)));
  return all.some((bal) => bal > cost * 2n);
}

export interface ReturnResult {
  hashes: string[];
  returned: bigint;
  /** Burners whose return failed (they keep their funds: retry, or export the keys). */
  failed: { label: string; address: string; error: string }[];
}

/** Every burner sends what it holds, minus its transfer fee, back to the funder; each burner on its own (one
 *  failure does not hide the others). */
export async function returnLeftovers(base: LiveBase, b: Burners): Promise<ReturnResult> {
  const provider = liveProvider(base);
  const { maxFeePerGas, maxPriorityFeePerGas, cost } = await returnFee(provider);
  const list = burnerAddresses(b);
  const out = await Promise.allSettled(
    list.map(async (x) => {
      const bal = await provider.getBalance(x.address);
      if (bal <= cost * 2n) return null;
      const w = new Wallet(x.key, provider);
      const tx = await w.sendTransaction({ to: b.funder, value: bal - cost, gasLimit: 21_000n, maxFeePerGas, maxPriorityFeePerGas, chainId: LIVE_CHAIN_ID });
      await tx.wait();
      return { hash: tx.hash, value: bal - cost };
    }),
  );
  const r: ReturnResult = { hashes: [], returned: 0n, failed: [] };
  out.forEach((o, i) => {
    if (o.status === "rejected") r.failed.push({ label: list[i]!.label, address: list[i]!.address, error: String((o.reason as Error)?.message ?? o.reason) });
    else if (o.value) (r.hashes.push(o.value.hash), (r.returned += o.value.value));
  });
  return r;
}

/** JSON export of the burner keys (testnet only), for the user to keep or recover funds elsewhere. */
export function exportBurners(b: Burners): string {
  return JSON.stringify(
    {
      warning: "Testnet burner keys (Base Sepolia 84532). Never send real funds to these addresses.",
      chainId: b.chainId,
      funder: b.funder,
      registry: b.registry ?? null,
      examLabel: b.examLabel,
      created: b.created,
      wallets: burnerAddresses(b).map(({ label, address, key }) => ({ label, address, privateKey: key })),
    },
    null,
    2,
  );
}
