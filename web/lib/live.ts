  const office = acct(b.keys.office);
  const demo: DemoState = {
    examId: toBytes32Id(b.examLabel),
    examTitle: EXAM_TITLE,
    subject: SUBJECT,
    rounds: ZERO_ROUNDS,
    announcedCentreCount: CENTRE_NAMES.length,
    office,
    committees: b.keys.committees.map((k, i) => ({ ...acct(k), setIndex: i, label: LABELS[i]! })),
    reserveCommittee: { ...acct(b.keys.reserve), setIndex: b.keys.committees.length, label: "R" },
    centres: b.keys.centres.map((k, i) => ({ ...acct(k), centreId: toBytes32Id(`centre:${CENTRE_NAMES[i]}`), name: CENTRE_NAMES[i]!, identity: "", recipient: "", rcHex: "" })),
    packages: [],
    phantom: PHANTOM,
    juror: acct(b.keys.juror),
  };
  return liveConfig(base, b.registry, office.address, demo);
