/** Forget the solo test of this browser: its burner keys and the centre identities and r_c of its registry. The
 *  centre keys of the shared registry (wallet mode) are never deleted here. The caller ends a solo session. */
export function forgetSolo(b: Burners): void {
  storage.remove(TESTNET_NS + "burners");
  const reg = b.registry?.toLowerCase();
  if (!reg) return;
  for (const k of storage.keys(TESTNET_NS)) {
    const rest = k.slice(TESTNET_NS.length);
    if (rest.startsWith(`identity.${reg}.`) || rest.startsWith(`rc.${reg}.`)) storage.remove(k);
  }
}

