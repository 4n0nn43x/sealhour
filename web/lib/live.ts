/** Connected wallet on the shared registry: the latest exam (or a fresh label), accounts from chain, no keys. */
export async function walletConfig(base: LiveBase): Promise<AppConfig> {
  const empty: DemoState = {
    examId: toBytes32Id(SHARED_EXAM_LABEL),
    examTitle: "Live exam",
    subject: "Base Sepolia",
    rounds: ZERO_ROUNDS,
    announcedCentreCount: 0,
    office: { address: base.registry.office, privateKey: null },
    committees: [],
    reserveCommittee: { address: "", privateKey: null, setIndex: 0, label: "R" },
    centres: [],
    packages: [],
    phantom: PHANTOM,
  };
  const cfg0 = liveConfig(base, base.registry.address, base.registry.office, empty);
  if (String(await registry(cfg0).beaconChainHash()).replace(/^0x/i, "").toLowerCase() !== QUICKNET_PIN.chainHash) throw new Error("BeaconPinMismatch");
  const ids: string[] = [...(await registry(cfg0).examIds())];
  const examId = ids[ids.length - 1] ?? empty.examId;
  const snap = await readSnapshot(cfg0, examId);
  const all = snap.exam.frozen ? snap.centres : await readAllCentres(cfg0);
  const [committees, reserve] = await registry(cfg0).committeesOf(examId);
  const demo: DemoState = {
    ...empty,
    examId,
    examTitle: ids.length ? "Live exam" : empty.examTitle,
    announcedCentreCount: snap.exam.frozen ? snap.exam.centreCount : all.length,
    committees: [...committees].map((address: string, i: number) => ({ address, privateKey: null, setIndex: i, label: LABELS[i] ?? String.fromCharCode(65 + i) })),
    reserveCommittee: { address: reserve, privateKey: null, setIndex: committees.length, label: "R" },
    centres: all.map((c) => ({ centreId: c.centreId, name: c.name, address: c.operator, privateKey: null, identity: "", recipient: "", rcHex: "" })),
  };
  return liveConfig(base, base.registry.address, base.registry.office, demo);
}

